// 小阿尔克那的深度解读：采用《塔羅解牌研究所》体系的手工知识库（tarotBook.js），
// 每张牌含牌面意象 image 与独立的手工 love/career/revAdvice，取代旧版"花色×数字"空泛合成。

import { getBook } from './tarotBook.js'

// 导出完整深度卡库：以牌 id 为 key
export const DEEP_CARD = {}

// 大牌：直接注入（MAJOR_DEEP 在下方，见本文件顶部），并补充 tarotBook 的牌面意象 image
for (const [id, deep] of Object.entries(MAJOR_DEEP)) {
  const book = getBook(id)
  DEEP_CARD[id] = book ? { ...deep, image: book.image } : deep
}

// 小牌：采用 tarotBook 手工解读（w=权杖, c=圣杯, s=宝剑, p=星币）
const SUIT_KEY = { wands: 'w', cups: 'c', swords: 's', pentacles: 'p' }
for (const [suit, key] of Object.entries(SUIT_KEY)) {
  for (let num = 1; num <= 14; num++) {
    const id = `${key}${num}`
    const book = getBook(id)
    DEEP_CARD[id] = book
      ? {
          love: book.love,
          loveRev: book.loveRev,
          career: book.career,
          careerRev: book.careerRev,
          yesNo: book.yesNo,
          yesNoRev: book.yesNoRev,
          revAdvice: book.revAdvice,
          // 牌面意象：供"单卡详解/牌意对照"场景展示
          image: book.image,
        }
      : null
  }
}

// 便捷取用：找不到时回退 null
export function getDeep(id) {
  return DEEP_CARD[id] || null
}

// 便捷取用牌面意象（供详情页展示）
export function getImage(id) {
  return getDeep(id)?.image || ''
}
