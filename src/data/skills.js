// 收敛到 wuyunliuqi。
export const SKILL_KEY_ALIASES = Object.freeze({ health: 'wuyunliuqi' })

export function canonicalSkillKey(key) {
  const raw = String(key || '').trim()
  return SKILL_KEY_ALIASES[raw] || raw
}

export function normalizeEnabledSkillKeys(keys) {
  if (!Array.isArray(keys)) return []
  return [...new Set(keys
    .map(canonicalSkillKey)
    .filter(Boolean))]
}

// 五运六气的排盘工具依赖出生资料；合并后的日常养护咨询没有生辰时，
// 应直接走通用生活建议，不能把“缺少出生信息”当作回答主体。
export function shouldRunSkillTool(skill, chart) {
  if (!skill?.tool) return false
  if (skill.key === 'wuyunliuqi') return Array.isArray(chart?.pillars) && chart.pillars.length === 4
  return true
}

