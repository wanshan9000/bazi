export function skillByKey(key, customSkills) {
  const canonicalKey = canonicalSkillKey(key)
  const custom = (customSkills || []).find(s => s.key === canonicalKey)
  if (custom) return custom
  return BUILTIN_SKILLS.find(s => s.key === canonicalKey)
}

// ---------- 自定义技能 ----------
// 来源有两类：
//  1. 【管理后台导入】管理员在后台上传/导入的技能，存后端 JSON 全站共享；
//     前端启动时异步拉取并缓存到 localStorage（genki-admin-skills），
//     loadCustomSkills 同步返回该缓存，供 Agent 路由与启用判定使用。
//  2. 普通用户手写技能已停用（历史遗留被清理），agent 自我进化技能由
//     agentEvolve 提供（loadEvolvedSkills / evolvedSkill）。
const LS_ADMIN = 'genki-admin-skills'

// 读取本地缓存的管理后台技能
export function loadAdminSkills() {
  try {
    const raw = localStorage.getItem(LS_ADMIN)
    if (!raw) return []
    const arr = JSON.parse(raw)
    return Array.isArray(arr) ? arr : []
  } catch { return [] }
}

// 写入本地缓存（供 loadCustomSkills 同步返回）
export function saveAdminSkills(skills) {
  try { localStorage.setItem(LS_ADMIN, JSON.stringify(skills || [])) } catch { /* ignore */ }
}

// 同步返回当前可用技能池（管理后台导入的已启用技能）。
// 标记 _admin：agentSkills 据此认定该技能由管理员审核、其 sys 可注入（仍带优先级锁定）。
export function loadCustomSkills() {
  return loadAdminSkills()
    .filter(s => s.enabled !== false)
    .map(s => ({ ...s, _admin: true }))
}

// 异步拉取后端全站技能并刷新本地缓存；后端不可用时静默失败，保留旧缓存。
export async function syncAdminSkills() {
  try {
    const r = await api.adminSkills()
    if (r && Array.isArray(r.data)) saveAdminSkills(r.data)
    return r?.data || []
  } catch { return loadAdminSkills() }
}

export function allSkills(customSkills) {
  return [...BUILTIN_SKILLS, ...(customSkills || [])]
}

export function detectSkill(text, enabledSkills, customSkills) {
  if (!enabledSkills || !enabledSkills.length) return null
  const q = text.trim()
  for (const key of normalizeEnabledSkillKeys(enabledSkills)) {
    const skill = skillByKey(key, customSkills)
    if (!skill || !skill.keywords) continue
    if (skill.keywords.some(kw => q.includes(kw))) return skill
  }
  return null
}
